#!/usr/bin/env python3
"""Bounded generic-VM regression for lab ABI/labels/configfs. Never a tablet test."""
import argparse
import gzip
import hashlib
import json
import os
from pathlib import Path
import re
import selectors
import shutil
import subprocess
import time
from build_diagnostic_initramfs import archive, inspect_elf
from build_lab_log_initramfs import inspect_archive

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'projects/firetabs-android/diagnostic-usb'
PROBE = ROOT / 'tests/fixtures/lab_policy_vm_probe.c'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def parse_log(data):
    text = data.replace(b'\r\n', b'\n')
    expected_zero = ['VM_DOMAIN', 'VM_LABELS', 'VM_PROC', 'VM_SYS', 'VM_CONFIGFS', 'VM_NAMESPACE_BEFORE',
                     'VM_REAL_CONFIGFS_SETUP_WITHOUT_BIND', 'VM_REAL_CONFIGFS_CLEANUP', 'VM_NAMESPACE_AFTER']
    expected = set(expected_zero + ['VM_KMSG_OPEN', 'VM_KMSG_READ', 'VM_UDC_DIR', 'VM_GENERIC_FLAGS_OPEN'])
    values = {}
    for key, value in re.findall(rb'^(VM_[A-Z_]+)=([+-][0-9]{10})$', text, re.M):
        key = key.decode()
        if key not in expected:
            continue
        if key in values:
            raise ValueError('Duplicate VM regression marker')
        values[key] = int(value)
    if (set(values) != expected or any(values[k] for k in expected_zero)
            or values['VM_KMSG_OPEN'] < 0 or values['VM_UDC_DIR'] < 0 or values['VM_KMSG_READ'] <= 0
            or values['VM_GENERIC_FLAGS_OPEN'] != -22 or text.count(b'VM_FILESYSTEM_PROBE_DONE') != 1
            or any(token in text for token in [b'avc:  denied', b'Kernel panic', b'Internal error: Oops'])):
        raise ValueError('Enforcing VM ABI/label/filesystem regression failed')
    return values


def generated_header(data, component):
    arrays = re.findall(rb'static const unsigned char (lab_policy_blob|lab_trial_nonce)\[\]=\{\n([0-9a-fx,\n]+)\n\};\n', data)
    if len(arrays) != 2 or b''.join(b'static const unsigned char ' + n + b'[]={\n' + body + b'\n};\n' for n, body in arrays) != data:
        raise ValueError('Unexpected generated input syntax')
    values = {}
    for name, body in arrays:
        tokens = body.replace(b'\n', b'').split(b',')
        if any(not re.fullmatch(rb'0x[0-9a-f]{2}', token) for token in tokens):
            raise ValueError('Unexpected generated byte')
        values[name.decode()] = bytes(int(token, 16) for token in tokens)
    if (not 24 <= len(values.get('lab_policy_blob', b'')) <= 65536
            or len(values.get('lab_trial_nonce', b'')) != 32
            or sha(values['lab_policy_blob']) != component['policy_sha256']
            or sha(values['lab_trial_nonce']) != component['nonce_sha256']):
        raise ValueError('Generated policy/nonce identity mismatch')
    return data


def run(kernel, expected_kernel, component_dir, output, entry_framebuffer_ram=False):
    if output.exists() or output.is_symlink():
        raise ValueError('Fresh private VM output required')
    if kernel.is_symlink() or not kernel.is_file() or not 64 <= kernel.stat().st_size <= 32 * 1024 * 1024:
        raise ValueError('Bounded regular retained kernel required')
    if not re.fullmatch(r'[0-9a-f]{64}', expected_kernel) or sha(kernel.read_bytes()) != expected_kernel:
        raise ValueError('Exact reviewed retained kernel hash required')
    component = json.loads((component_dir / 'report.json').read_text())
    for name, expected in component['sources_sha256'].items():
        if Path(name).name != name or sha((SOURCE / name).read_bytes()) != expected:
            raise ValueError('Component source drift')
    header = generated_header((component_dir / 'lab_inputs.h').read_bytes(), component)
    qemu, cc, linker = (shutil.which(n) for n in ['qemu-system-aarch64', 'clang-18', 'ld.lld-18'])
    if not all([qemu, cc, linker]):
        raise ValueError('Explicit QEMU and LLVM18 host tools required')
    output.mkdir(mode=0o700, parents=True)
    (output / 'lab_inputs.h').write_bytes(header)
    elf = output / 'init'
    result = subprocess.run([cc, '--target=aarch64-linux-gnu', '--ld-path=' + linker, '-nostdlib', '-static',
                             '-Os', '-ffreestanding', '-fno-builtin', '-fno-stack-protector', '-mgeneral-regs-only',
                             '-Wl,--build-id=none,-e,_start', '-I', str(SOURCE), '-I', str(output),
                             '-o', str(elf), str(PROBE), str(SOURCE / 'memory.c')],
                            capture_output=True, timeout=45)
    (output / 'compile-private.log').write_bytes(result.stdout + result.stderr)
    if result.returncode:
        raise ValueError('VM probe compilation failed')
    inspect_elf(elf.read_bytes())
    entries = [(n, 0o040755, b'', (0, 0)) for n in ['dev', 'proc', 'sys', 'security', 'config']]
    entries += [('dev/console', 0o020600, b'', (5, 1)), ('dev/kmsg', 0o020400, b'', (1, 11)),
                ('init', 0o100500, elf.read_bytes(), (0, 0))]
    raw = archive(entries)
    inspect_archive(raw, entries)
    initramfs = output / 'initramfs.cpio.gz'
    initramfs.write_bytes(gzip.compress(raw, mtime=0))
    command = [qemu, '-machine', 'virt,gic-version=2', '-cpu', 'cortex-a53', '-smp', '1', '-m', '1536' if entry_framebuffer_ram else '512',
               '-nodefaults', '-display', 'none', '-serial', 'stdio', '-monitor', 'none', '-nic', 'none',
               '-no-reboot', '-kernel', str(kernel), '-initrd', str(initramfs), '-append',
               'console=ttyAMA0,115200 earlycon=pl011,0x9000000 rdinit=/init nr_cpus=1 maxcpus=0 loglevel=8 ignore_loglevel panic=-1']
    proc = subprocess.Popen(command, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    data = bytearray()
    selector = selectors.DefaultSelector()
    selector.register(proc.stdout, selectors.EVENT_READ)
    end = time.monotonic() + 20
    try:
        while time.monotonic() < end:
            for key, _ in selector.select(.1):
                chunk = os.read(key.fileobj.fileno(), 65536)
                if not chunk:
                    end = 0
                    break
                data.extend(chunk)
                if len(data) > 2 * 1024 * 1024:
                    raise ValueError('VM log budget exceeded')
            if proc.poll() is not None:
                break
    finally:
        if proc.poll() is None:
            proc.terminate()
            try:
                proc.wait(timeout=3)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait(timeout=3)
        selector.close()
        proc.stdout.close()
        (output / 'serial-private.log').write_bytes(data)
        for path in output.iterdir():
            if path.is_file():
                path.chmod(0o600)
    values = parse_log(bytes(data))
    report = {'scope': 'Generic VM ABI/label/configfs regression only; no tablet handoff or USB hardware test',
              'passed': True, 'kernel_sha256': expected_kernel, 'policy_sha256': component['policy_sha256'],
              'probe_source_sha256': sha(PROBE.read_bytes()), 'runner_sha256': sha(Path(__file__).read_bytes()),
              'vm_initramfs_sha256': sha(initramfs.read_bytes()), 'values': values,
              'ram_mib': 1536 if entry_framebuffer_ram else 512, 'cpu_count': 1, 'wall_limit_seconds': 20, 'log_limit_bytes': 2 * 1024 * 1024,
              'qemu_version': subprocess.check_output([qemu, '--version'], text=True).splitlines()[0],
              'selinux_enforcing': True, 'udc_bind_intercepted_vm_only': True,
              'disk_attached': False, 'network_attached': False, 'tablet_commands': False,
              'kernel_rebuilt': False, 'physical_execution_admitted': False}
    (output / 'report.json').write_text(json.dumps(report, indent=2) + '\n')
    (output / 'report.json').chmod(0o600)
    return report


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--kernel', type=Path, required=True)
    p.add_argument('--expected-kernel-sha256', required=True)
    p.add_argument('--component-dir', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--entry-framebuffer-ram', action='store_true')
    a = p.parse_args()
    try:
        print(json.dumps(run(a.kernel, a.expected_kernel_sha256, a.component_dir, a.output, entry_framebuffer_ram=a.entry_framebuffer_ram), indent=2))
    except (OSError, ValueError, KeyError, subprocess.SubprocessError):
        p.exit(2, 'VM regression stopped; inspect private output. No tablet operation.\n')


if __name__ == '__main__':
    main()
